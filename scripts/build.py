"""
Builds the Windows app and installer. The version is read from pyproject.toml and never modified here,
bump it on purpose with `uv version --bump patch|minor|major`.

    uv run python scripts/build.py                  # app + installer (if Inno Setup is installed)
    uv run python scripts/build.py --no-installer   # app only

Outputs: dist/pol-tax/ (the app) and dist/Pol-Tax_<version>.exe (the installer).
"""
import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from Other.Version import app_version, windows_version_tuple  # noqa: E402

BUILD_DIR = ROOT / "build"
DIST_DIR = ROOT / "dist"
GENERATED_VERSION_MODULE = ROOT / "Other" / "_version.py"
VERSION_INFO_FILE = BUILD_DIR / "file_version_info.txt"
ISS_FILE = ROOT / "installer" / "pol-tax.iss"
ISCC_LOCATIONS = [
    Path(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)")) / "Inno Setup 6" / "ISCC.exe",
    Path(os.environ.get("ProgramFiles", r"C:\Program Files")) / "Inno Setup 6" / "ISCC.exe",
    Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "Inno Setup 6" / "ISCC.exe",
]

VERSION_INFO_TEMPLATE = """# UTF-8
# Generated by scripts/build.py, do not edit
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={version_tuple},
    prodvers={version_tuple},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
    ),
  kids=[
    StringFileInfo(
      [
      StringTable(
        '041504b0',
        [StringStruct('CompanyName', 'Pol-Tax'),
        StringStruct('FileDescription', 'Pol-Tax'),
        StringStruct('FileVersion', '{version_dotted}'),
        StringStruct('InternalName', 'pol-tax'),
        StringStruct('OriginalFilename', 'pol-tax.exe'),
        StringStruct('ProductName', 'Pol-Tax'),
        StringStruct('ProductVersion', '{version}')])
      ]),
    VarFileInfo([VarStruct('Translation', [1045, 1200])])
  ]
)
"""


def step(message):
    print(f"==> {message}", flush=True)


def run(*args):
    subprocess.run([str(a) for a in args], cwd=ROOT, check=True)


def find_iscc():
    found = shutil.which("ISCC") or shutil.which("iscc")
    if found:
        return Path(found)
    return next((path for path in ISCC_LOCATIONS if path.exists()), None)


def main():
    arg_parser = argparse.ArgumentParser(description="Build Pol-Tax")
    arg_parser.add_argument("--no-installer", action="store_true", help="Skip the Inno Setup installer")
    arg_parser.add_argument("--build-number", type=int, default=int(os.environ.get("BUILD_NUMBER", "0")),
                            help="Fourth part of the Windows file version (CI passes its run number)")
    args = arg_parser.parse_args()

    version = app_version()
    version_tuple = windows_version_tuple(version, args.build_number)
    step(f"Building Pol-Tax {version} (file version {'.'.join(map(str, version_tuple))})")

    step("Cleaning build/ and dist/")
    shutil.rmtree(BUILD_DIR, ignore_errors=True)
    shutil.rmtree(DIST_DIR, ignore_errors=True)
    BUILD_DIR.mkdir()

    step("Generating version files")
    GENERATED_VERSION_MODULE.write_text(f'# Generated by scripts/build.py, do not edit\nVERSION = "{version}"\n',
                                        encoding="utf8")
    VERSION_INFO_FILE.write_text(VERSION_INFO_TEMPLATE.format(version=version, version_tuple=version_tuple,
                                                              version_dotted=".".join(map(str, version_tuple))),
                                 encoding="utf8")

    try:
        step("Running PyInstaller")
        run(sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
            "--distpath", DIST_DIR, "--workpath", BUILD_DIR / "pyinstaller", ROOT / "pol-tax.spec")
    finally:
        # Running from source must keep reading pyproject.toml
        GENERATED_VERSION_MODULE.unlink(missing_ok=True)

    if args.no_installer:
        step("Skipping installer")
    else:
        iscc = find_iscc()
        if iscc is None:
            step("Inno Setup not found, skipping installer (winget install JRSoftware.InnoSetup)")
        else:
            step("Building installer")
            run(iscc, f"/DMyAppVersion={version}", f"/O{DIST_DIR}", ISS_FILE)

    step("Done:")
    for path in sorted(DIST_DIR.iterdir()):
        print(f"    {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
